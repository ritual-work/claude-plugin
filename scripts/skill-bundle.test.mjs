import assert from "node:assert/strict";
import { readFileSync, readdirSync } from "node:fs";
import { test } from "node:test";

const root = new URL("../plugins/ritual/", import.meta.url);
const read = (path) => readFileSync(new URL(path, root), "utf8");

// SKILL.md plus every Markdown file under references/, phase subfolders included.
const bundleFiles = () => [
  "SKILL.md",
  ...readdirSync(new URL("skills/build/references/", root), { recursive: true })
    .filter((name) => name.endsWith(".md"))
    .map((name) => `references/${name}`),
];

test("public Claude skill retains its namespace, channel and source stamp", () => {
  const skill = read("skills/build/SKILL.md");
  const stamp = JSON.parse(read(".skill-stamp.json"));
  assert.match(skill, /^name: build$/m);
  assert.match(skill, /^channel: claude-plugin$/m);
  assert.ok(skill.includes(`stamp: ${stamp.stamp}\n`));
  // The stamp only matters if the bundle still performs the ping handshake that sends it.
  assert.ok(read("skills/build/references/session-rules.md").includes("`skill_stamp`"));
  assert.ok(read("skills/build/references/build-flow/entry.md").includes("mcp__ritual__ping"));
});

test("skill routes plain questions to the current MCP tool names", () => {
  const skill = read("skills/build/SKILL.md");
  for (const tool of [
    "get_exploration_status",
    "list_explorations",
    "get_recommendations",
    "start_discovery_run",
    "get_file_lineage",
  ]) {
    assert.ok(skill.includes(`mcp__ritual__${tool}`), `SKILL.md routes to mcp__ritual__${tool}`);
  }
  // Names retired by the tool-surface rename must not resurface anywhere in the bundle.
  for (const file of bundleFiles()) {
    assert.doesNotMatch(
      read(`skills/build/${file}`),
      /start_agentic_run|get_agentic_run|generate_problem_statement|query_knowledge_graph/,
      file,
    );
  }
});

test("shared public scrub preserves runtime templates and removes authoring prose", () => {
  // build-flow.md is a dispatcher; the call shapes live in the phase files it points at.
  const dispatcher = read("skills/build/references/build-flow.md");
  assert.ok(dispatcher.includes("`references/build-flow/brief.md`"));
  const brief = read("skills/build/references/build-flow/brief.md");
  assert.ok(brief.includes("call `mcp__ritual__sync_brief_review` with:"));
  assert.ok(brief.includes("   {\n     exploration_id,\n     review_type: 'BRIEF_VERIFICATION',"));
  assert.ok(brief.includes("   {\n     exploration_id,\n     review_type: 'UX_REVIEW',"));
  assert.ok(brief.includes("Generated by Ritual"));
  // Same scope as the scrub pass in scripts/sync-ritual-skill.mjs.
  const files = [
    "SKILL.md",
    ...readdirSync(new URL("skills/build/references/", root), { recursive: true })
      .filter((name) => typeof name === "string" && name.endsWith(".md"))
      .map((name) => `references/${name}`),
  ];
  for (const file of files) {
    assert.doesNotMatch(
      read(`skills/build/${file}`),
      /\bSpark\b|skill-options:|skill-flow:|no_render_leaks|both PR B\/C/,
    );
  }
});

test("missing upstream scrubber leaves the installed bundle untouched", async () => {
  const { mkdtempSync, mkdirSync, writeFileSync, cpSync, rmSync } = await import("node:fs");
  const { tmpdir } = await import("node:os");
  const { join } = await import("node:path");
  const { spawnSync } = await import("node:child_process");
  const temp = mkdtempSync(join(tmpdir(), "ritual-sync-preflight-"));
  try {
    const script = join(temp, "plugin/scripts/sync-ritual-skill.mjs");
    const upstream = join(temp, "upstream");
    const sentinel = join(temp, "plugin/plugins/ritual/skills/build/SKILL.md");
    mkdirSync(join(temp, "plugin/scripts"), { recursive: true });
    mkdirSync(join(upstream, "apps/cli/scripts"), { recursive: true });
    mkdirSync(join(temp, "plugin/plugins/ritual/skills/build"), { recursive: true });
    cpSync(new URL("sync-ritual-skill.mjs", import.meta.url), script);
    writeFileSync(join(upstream, "apps/cli/scripts/build-skills.js"), "throw new Error('must not build');");
    writeFileSync(sentinel, "existing bundle\n");
    const result = spawnSync(process.execPath, [script, upstream], { encoding: "utf8" });
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /upstream public scrubber missing/);
    assert.equal(readFileSync(sentinel, "utf8"), "existing bundle\n");
  } finally {
    rmSync(temp, { recursive: true, force: true });
  }
});
